export interface RulesParityGradeResult {
  passed: boolean;
  score: number;
  hasZeroEmoji: boolean;
  hasZeroLockIn: boolean;
  has3TierLocators: boolean;
  hasCpomMethodSafety: boolean;
  violations: string[];
}

/**
 * Deterministic Grader for Multi-Assistant Rules Parity & Quality.
 */
export function gradeRulesParity(content: string): RulesParityGradeResult {
  const violations: string[] = [];
  let checksTotal = 0;
  let checksPassed = 0;

  // 1. Zero Emoji check
  checksTotal++;
  const emojiRegex = /[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}]/u;
  const hasZeroEmoji = !emojiRegex.test(content);
  if (!hasZeroEmoji) {
    violations.push('Rule Violation: Zero-Emoji policy violated in rule content.');
  } else {
    checksPassed++;
  }

  // 2. Zero Lock-in check
  checksTotal++;
  const lockInRegex = /created by eitr|generated by eitr|eitr is a proprietary/i;
  const hasZeroLockIn = !lockInRegex.test(content);
  if (!hasZeroLockIn) {
    violations.push('Rule Violation: Zero Lock-in rule violated (mentions creator/EITR).');
  } else {
    checksPassed++;
  }

  // 3. 3-Tier Locator Priority check
  checksTotal++;
  const has3TierLocators = /getByTestId|3-Tier|Locator Priority|locator|data-testid/i.test(content);
  if (!has3TierLocators) {
    violations.push('Rule Violation: Missing 3-Tier Locator Priority specification.');
  } else {
    checksPassed++;
  }

  // 4. CPOM Method Safety check
  checksTotal++;
  const hasCpomMethodSafety = /Now\(\)|Component|Page Object|POM|Framework/i.test(content);
  if (!hasCpomMethodSafety) {
    violations.push('Rule Violation: Missing CPOM Method Safety specifications.');
  } else {
    checksPassed++;
  }

  const score = Math.round((checksPassed / Math.max(checksTotal, 1)) * 100);
  const passed = violations.length === 0;

  return {
    passed,
    score,
    hasZeroEmoji,
    hasZeroLockIn,
    has3TierLocators,
    hasCpomMethodSafety,
    violations,
  };
}
