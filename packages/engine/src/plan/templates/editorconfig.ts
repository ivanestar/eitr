// .editorconfig for the generated project (create-if-absent). Makes indentation and line endings
// render and save consistently across editors — so the code always looks the way it was generated.
export function renderEditorConfig(): string {
  return `root = true

[*]
charset = utf-8
end_of_line = lf
indent_style = space
indent_size = 2
insert_final_newline = true
trim_trailing_whitespace = true
`;
}
